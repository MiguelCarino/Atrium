#!/usr/bin/env python3
"""hyprlock_theme -- the lock screen in the desktop theme's colours and fonts.

~/.config/hypr/hyprlock.conf (the lock's layout, which lock-screen.py and
Settings > Wallpaper & lock screen edit) sets its colours and fonts through
variables -- $lock_accent, $lock_text, $font_display, ... -- defines the
cyberpunk values for them first, and then sources this file's output:

    ~/.config/waybar/generated/hyprlock-theme.conf

which redefines them for the current theme. theme.py writes it with the rest
of a theme's generated files, in the same folder (write_generated: every
`theme.py set`, and `theme.py ensure` when it is missing). hyprlock reads its config at every
lock, so a theme switch shows at the next lock with nothing to restart.
A missing file leaves the cyberpunk defaults (hyprlock logs the failed
source and goes on), so the lock always has a password field and a clock.

    hyprlock_theme.py [THEME]     print the include for THEME (default: the
                                  current one) -- what theme.py would write
    hyprlock_theme.py --write     write it for the current theme

Where the values come from (a theme needs no keys of its own):
  cyberpunk     the neon set the lock was drawn in: Orbitron / Rajdhani /
                Share Tech Mono, cyan with magenta, a glow on every label.
  every other   its own fonts (font=, font_mono=), its accent (accent=, else
                cosmic.accent), text and surface from cosmic.foreground /
                cosmic.background (else term.*), its danger and sun colours
                for a failed try and Caps Lock, and hypr.rounding for the
                field's corners. The lock always sits on a DIMMED picture
                (hyprlock.conf's background brightness), so a light theme's
                surface and text are swapped round -- its light background
                becomes the text -- and an accent too dark to read on the
                field is lifted towards white until it reaches 3:1.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "hyprlock-theme.conf"
OUT = os.path.join(os.path.expanduser("~/.config/waybar/generated"), NAME)   # theme.py's GEN
MARK = "GENERATED by ~/.config/hypr/scripts/theme.py (hyprlock_theme.py)"
BASE = "cyberpunk"

# The neon lock as it was hand-drawn in hyprlock.conf, which keeps the same
# values as its own defaults.
NEON = {
    "font_display": "Orbitron",
    "font_text": "Rajdhani SemiBold",
    "font_mono": "Share Tech Mono",
    "lock_accent": "rgb(00f0ff)",
    "lock_second": "rgb(ff2a6d)",
    "lock_text": "rgb(00f0ff)",
    "lock_dim": "rgba(00f0ff99)",
    "lock_inner": "rgba(060810d9)",
    "lock_check": "rgb(f9f002)",
    "lock_fail": "rgb(ff2a6d)",
    "lock_alarm": "rgb(b026ff)",
    "lock_caps": "rgb(f9f002)",
    "lock_glow": "rgba(00f0ff99)",
    "lock_shadow": "rgba(ff2a6d8c)",
    "lock_halo": "rgba(00f0ff73)",
    "lock_rounding": "4",
    "lock_prompt": "ENTER PASSWORD_",
    "lock_date": "%^A // %d %^B",
}


def hex_rgb(value):
    v = value.strip().lstrip("#")
    return [int(v[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def rgb_hex(rgb):
    return "".join(f"{round(max(0, min(1, c)) * 255):02x}" for c in rgb)


def mix(a, b, t):
    """t of the way from #a to #b, as #rrggbb."""
    return "#" + rgb_hex([x + (y - x) * t for x, y in zip(hex_rgb(a), hex_rgb(b))])


def luminance(rgb):
    def lin(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(hex_rgb(a)), luminance(hex_rgb(b))), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def is_hex(value):
    v = (value or "").strip().lstrip("#")
    return len(v) == 6 and all(c in "0123456789abcdefABCDEF" for c in v)


def readable(colour, on, floor=3.0):
    """colour, lifted towards white in steps until it reads at `floor`:1 on
    `on` (or white, if nothing short of it does)."""
    for step in range(11):
        c = mix(colour, "#ffffff", step / 10)
        if contrast(c, on) >= floor:
            return c
    return "#ffffff"


def rgb(c):
    return f"rgb({c.lstrip('#').lower()})"


def rgba(c, alpha):
    return f"rgba({c.lstrip('#').lower()}{round(alpha * 255):02x})"


def first(conf, *keys, default):
    for k in keys:
        if is_hex(conf.get(k)):
            return "#" + conf[k].strip().lstrip("#")
    return default


def values(conf):
    """{variable name (no $): value} for theme conf `conf` (theme.load())."""
    if conf.get("id", BASE) == BASE:
        return dict(NEON)
    bg = first(conf, "cosmic.background", "term.background", default="#0d1018")
    fg = first(conf, "cosmic.foreground", "term.foreground", default="#e6edf7")
    if contrast(bg, "#000000") > contrast(bg, "#ffffff"):
        # A light theme: on the dimmed lock its page colour (lifted half way
        # to white: a grey page reads dull as text) is the text, and a dark
        # surface is made from its own ink.
        fg, bg = mix(bg, "#ffffff", 0.5), mix(fg, "#000000", 0.45)
    accent = readable(first(conf, "accent", "cosmic.accent", default="#4aa3f0"), bg)
    accent2 = mix(accent, fg, 0.45)
    # These two are read as text (the failed-try line, the Caps Lock rim):
    # 4.5:1, the text floor, where the accent -- an outline -- needs 3.
    fail = readable(first(conf, "color.danger", default="#ff5c6c"), bg, 4.5)
    caps = readable(first(conf, "color.wx_sun", default="#ffd75e"), bg, 4.5)
    font = (conf.get("font") or "Sans").strip()
    mono = (conf.get("font_mono") or "Monospace").strip()
    try:
        rounding = max(0, min(27, int(float(conf.get("hypr.rounding", "8")))))
    except ValueError:
        rounding = 8
    return {
        "font_display": font,
        "font_text": font,
        "font_mono": mono,
        "lock_accent": rgb(accent),
        "lock_second": rgb(accent2),
        "lock_text": rgb(fg),
        "lock_dim": rgba(fg, 0.6),
        "lock_inner": rgba(bg, 0.85),
        "lock_check": rgb(accent2),
        "lock_fail": rgb(fail),
        "lock_alarm": rgb(mix(fail, bg, 0.3)),
        "lock_caps": rgb(caps),
        # No neon outside cyberpunk: a soft dark shadow, there to keep the
        # labels legible over a bright patch of the dimmed picture.
        "lock_glow": "rgba(00000099)",
        "lock_shadow": "rgba(00000080)",
        "lock_halo": rgba(accent, 0.30),
        "lock_rounding": str(rounding),
        "lock_prompt": "Password",
        "lock_date": "%A, %d %B",
    }


def text(conf):
    """The include, for theme conf `conf`."""
    name = conf.get("id", BASE)
    lines = [f"# {MARK} from theme '{name}' -- do not edit.",
             "# Sourced by ~/.config/hypr/hyprlock.conf after its own (cyberpunk)",
             "# defaults; a theme switch rewrites it."]
    for key, value in values(conf).items():
        # hyprlang: # starts a comment, ## is a literal #.
        lines.append(f"${key} = {value.replace('#', '##')}")
    return "\n".join(lines) + "\n"


def write(conf, path=OUT):
    """Atomic, only when it changed. True when written."""
    new = text(conf)
    try:
        with open(path) as handle:
            if handle.read() == new:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as handle:
        handle.write(new)
    os.replace(tmp, path)
    return True


def main(argv):
    sys.path.insert(0, HERE)
    import theme  # noqa: E402  (scripts/theme.py: load() resolves a theme)
    if argv[:1] == ["--write"]:
        print(OUT if write(theme.load()) else f"{OUT} (unchanged)")
        return 0
    if argv[:1] in (["-h"], ["--help"]):
        print(__doc__.strip())
        return 0
    sys.stdout.write(text(theme.load(argv[0] if argv else None)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
