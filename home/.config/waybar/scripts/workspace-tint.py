#!/usr/bin/env python3
"""Keep waybar's workspace pill colours pointed at the monitor each workspace is
on RIGHT NOW, instead of the one its hl.workspace_rule was born with.

Why this exists
---------------
style.css tints the pills by :nth-child, because that is the only handle GTK
gives us -- ext/workspaces emits .active, .urgent and .hidden and nothing else,
so there is no per-output class to select on. Position worked as long as every
workspace stayed on the monitor it was pinned to, and the comment in style.css
said as much: "IF YOU ADD, REMOVE OR RE-PIN A WORKSPACE, FIX THE NUMBERS BELOW."

ALT+n now summons empty workspaces across monitors (see summon() in
~/.config/hypr/lua/binds.lua), so re-pinning happens several times an hour rather than never.
Hand-maintained numbers cannot track that. This script writes them instead.

How
---
Two tiny CSS files under generated/, @import-ed from style.css at exactly the
two points the hand-written blocks used to sit. They have to stay two separate
files because the cascade around them is load-bearing: the unlit tint must come
BEFORE #workspaces button:hover (equal specificity, so later wins, and hover has
to be able to override the tint), while the lit tint must come AFTER
#workspaces button.active. One file could not be in both places.

waybar picks the change up on its own -- "reload_style_on_change": true in
config watches the stylesheet and every file it imports. No signal, no restart.

Verified before relying on it: GTK3 accepts an @import that is not the first
rule in the file, and @define-color declared in the parent resolves inside the
imported file (gtkmm-3.0, waybar 0.15.0).

Usage
-----
    workspace-tint.py once     write the files and exit
    workspace-tint.py watch    write, then follow Hyprland's event socket
"""

import json
import os
import select
import subprocess
import sys
import time

sys.path.insert(0, os.path.expanduser("~/.config/hypr/scripts"))
import screens  # noqa: E402  (hypr/scripts/screens.py: the screens in order)
import desk_common  # noqa: E402  (hypr/scripts/desk_common.py: hyprctl over the socket)
import hyprbus  # noqa: E402  (hypr/scripts/hyprbus.py: the shared event relay, or socket2 directly)

# Which @define-color each output's pills wear. Names match style.css: the
# screens in their order (screens.py order(): the host file's M.screens, else
# the live ones) wear mon1, mon2, mon3, mon4 -- the primary, the second screen,
# the third, the fourth (its workspace is 7, hypr/lua/workspaces.lua). An
# output past the fourth, or one the order does not know (a monitor
# plugged in later on a machine with a host file, say), falls back to
# @mon-unknown, the same neutral the strip already used for workspaces with
# no fixed home.
COLORS = ("mon1", "mon2", "mon3", "mon4")
FALLBACK = "mon-unknown"


def monitor_colors():
    """{output: colour name}, asked at every sync so a screen plugged in on a
    machine without a host file gets its colour."""
    return dict(zip(screens.order(), COLORS))

HOME = os.path.expanduser("~")
OUT_DIR = os.path.join(HOME, ".config", "waybar", "generated")
UNLIT = os.path.join(OUT_DIR, "workspace-tint.css")
LIT = os.path.join(OUT_DIR, "workspace-tint-active.css")

HEADER = (
    "/* GENERATED by scripts/workspace-tint.py -- do not edit.\n"
    "   Rewritten whenever a workspace changes monitor. */\n"
)

# Coalesce bursts: a single summon emits moveworkspace + workspace + focusedmon
# in quick succession, and rewriting on each one makes waybar reload the style
# three times for one visible change.
DEBOUNCE_S = 0.12

EVENTS = {
    "workspace", "workspacev2",
    "focusedmon", "focusedmonv2",
    "moveworkspace", "moveworkspacev2",
    "createworkspace", "createworkspacev2",
    "destroyworkspace", "destroyworkspacev2",
    "monitoradded", "monitoraddedv2",
    "monitorremoved", "monitorremovedv2",
    "configreloaded",
}


def hyprctl_workspaces():
    """Current workspaces, or None if Hyprland is not answering. Over the
    request socket: every workspace event used to start a hyprctl."""
    return desk_common.hypr_request("workspaces", json=True, timeout=2)


def pill_order(workspaces):
    """The workspaces waybar draws, in the order it draws them.

    Mirrors "sort-by-name": true. The module documents that numeric names sort
    numerically, so this does the same and only falls back to string order if
    something non-numeric shows up. Special workspaces are dropped: the
    scratchpad (special:magic) is not shown in this bar, so counting it would
    shift every position after it by one.
    """
    real = [w for w in workspaces if not str(w.get("name", "")).startswith("special")]
    if real and all(str(w["name"]).isdigit() for w in real):
        real.sort(key=lambda w: int(w["name"]))
    else:
        real.sort(key=lambda w: str(w["name"]))
    return real


def render(workspaces, colors=None):
    """Build both files' contents as (unlit, lit) strings. colors: {output:
    colour name}, monitor_colors() when not given."""
    colors = monitor_colors() if colors is None else colors
    by_color_unlit = {}
    by_color_lit = {}

    for pos, ws in enumerate(pill_order(workspaces), start=1):
        color = colors.get(ws.get("monitor"), FALLBACK)
        by_color_unlit.setdefault(color, []).append(pos)
        by_color_lit.setdefault(color, []).append(pos)

    def block(groups, selector_tmpl, prop, suffix):
        chunks = []
        for color in sorted(groups):
            sel = ",\n".join(selector_tmpl.format(n=n) for n in groups[color])
            chunks.append("%s {\n    %s: @%s%s;\n}\n" % (sel, prop, color, suffix))
        return HEADER + "\n" + "\n".join(chunks)

    unlit = block(
        by_color_unlit, "#workspaces button:nth-child({n})", "color", "-dim")
    lit = block(
        by_color_lit, "#workspaces button.active:nth-child({n})",
        "background-color", "")
    return unlit, lit


def write_if_changed(path, content):
    """Atomic, and a no-op when nothing moved.

    Both halves matter. Rewriting identical bytes would still bump mtime and
    make waybar reload its whole stylesheet for nothing -- and every workspace
    switch fires an event, so that would be constant. The temp-and-rename keeps
    waybar from ever reading a half-written file, since it is watching for
    exactly this change.
    """
    try:
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == content:
                return False
    except OSError:
        pass

    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.replace(tmp, path)
    return True


def sync():
    workspaces = hyprctl_workspaces()
    if workspaces is None:
        return False
    unlit, lit = render(workspaces)
    os.makedirs(OUT_DIR, exist_ok=True)
    changed = write_if_changed(UNLIT, unlit)
    changed |= write_if_changed(LIT, lit)
    return changed


def socket_path():
    sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
    runtime = os.environ.get("XDG_RUNTIME_DIR", "/run/user/%d" % os.getuid())
    base = os.path.join(runtime, "hypr")
    if not sig:
        try:
            sig = sorted(os.listdir(base))[-1]
        except (OSError, IndexError):
            return None
    return os.path.join(base, sig, ".socket2.sock")


def watch():
    sync()
    path = socket_path()
    if not path:
        sys.exit("workspace-tint: cannot locate Hyprland event socket")

    while True:
        try:
            sock = hyprbus.connect(EVENTS, direct=path)
        except OSError:
            # Hyprland is gone or not up yet. Retry rather than die: this is
            # started from the autostart block and should survive a restart.
            time.sleep(2)
            continue

        # Raw recv + select rather than sock.makefile().readline(). The buffered
        # reader cannot be combined with the socket timeout this loop needs to
        # implement the debounce: a timeout firing mid-read leaves the
        # BufferedReader inconsistent and the loop silently stops reacting
        # (observed -- the daemon stayed alive, Hyprland kept emitting
        # moveworkspace, and nothing was ever regenerated). select gives us the
        # same "wait, but not longer than DEBOUNCE_S" without touching the
        # socket's blocking mode.
        pending = False
        buf = b""
        with sock:
            while True:
                ready, _, _ = select.select(
                    [sock], [], [], DEBOUNCE_S if pending else None)
                if not ready:
                    sync()          # debounce elapsed, burst is over
                    pending = False
                    continue
                try:
                    data = sock.recv(65536)
                except OSError:
                    break
                if not data:
                    break
                buf += data
                while b"\n" in buf:
                    line, buf = buf.split(b"\n", 1)
                    name = line.split(b">>", 1)[0].decode(errors="replace")
                    if name in EVENTS:
                        pending = True
        time.sleep(1)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "once"
    if mode == "once":
        sync()
    elif mode == "watch":
        watch()
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
